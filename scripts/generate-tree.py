#!/usr/bin/env python3
"""Compile the final macOS-exported vector into GDI+ paths (stdout)."""
import hashlib
import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
source = ROOT / 'assets/tree-vector.svg'
root = ET.fromstring(source.read_bytes())
identity = (1., 0., 0., 1., 0., 0.)

def multiply(a, b):
    return (a[0]*b[0]+a[2]*b[1], a[1]*b[0]+a[3]*b[1],
            a[0]*b[2]+a[2]*b[3], a[1]*b[2]+a[3]*b[3],
            a[0]*b[4]+a[2]*b[5]+a[4], a[1]*b[4]+a[3]*b[5]+a[5])

def transform(text):
    result = identity
    for kind, raw in re.findall(r'(translate|rotate|scale)\(([^)]+)\)', text):
        v = [float(n) for n in raw.replace(',', ' ').split()]
        if kind == 'translate': m = (1, 0, 0, 1, v[0], v[1] if len(v)>1 else 0)
        elif kind == 'scale': m = (v[0], 0, 0, v[-1], 0, 0)
        else:
            c, s = math.cos(math.radians(v[0])), math.sin(math.radians(v[0]))
            m = (c, s, -s, c, 0, 0)
        result = multiply(result, m)
    return result

def number(n):
    value = f'{n:.6f}'.rstrip('0').rstrip('.')
    return '0' if value in ('', '-0') else value

def path_code(data, matrix):
    tokens = re.findall(r'[MLQCZ]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?', data)
    out = ['Gdiplus::GraphicsPath p;']
    cursor = start = (0., 0.)
    def point(v):
        x, y = v
        return 'point({' + number(matrix[0]*x+matrix[2]*y+matrix[4]) + ',' + number(matrix[1]*x+matrix[3]*y+matrix[5]) + '})'
    i = 0
    while i < len(tokens):
        command = tokens[i]; i += 1
        count = {'M': 2, 'L': 2, 'Q': 4, 'C': 6, 'Z': 0}[command]
        values = list(map(float, tokens[i:i+count])); i += count
        points = list(zip(values[::2], values[1::2]))
        if command == 'M': cursor = start = points[0]; out.append('p.StartFigure();')
        elif command == 'Z': out.append('p.CloseFigure();'); cursor = start
        elif command == 'L': out.append('p.AddLine('+point(cursor)+','+point(points[0])+');'); cursor = points[0]
        elif command == 'Q':
            c, end = points
            first = (cursor[0]+(c[0]-cursor[0])*2/3, cursor[1]+(c[1]-cursor[1])*2/3)
            second = (end[0]+(c[0]-end[0])*2/3, end[1]+(c[1]-end[1])*2/3)
            out.append('p.AddBezier('+','.join(map(point, [cursor,first,second,end]))+');'); cursor = end
        else: out.append('p.AddBezier('+','.join(map(point, [cursor]+points))+');'); cursor = points[-1]
    return out

layers = []
def walk(node, matrix=identity, alpha=1):
    matrix = multiply(matrix, transform(node.get('transform', '')))
    alpha *= float(node.get('opacity', 1))
    result = []
    if node.tag.endswith('path'):
        code = path_code(node.attrib['d'], matrix)
        fill, stroke = node.get('fill','none'), node.get('stroke','none')
        if fill != 'none':
            opacity = alpha * float(node.get('fill-opacity', 1))
            code += [f'Gdiplus::SolidBrush b(color(0x{fill[1:]},{number(opacity)}));', 'g.FillPath(&b,&p);']
        if stroke != 'none':
            opacity = alpha * float(node.get('stroke-opacity', 1))
            width = float(node.get('stroke-width', 1)) * math.hypot(matrix[0],matrix[1])
            code += [f'Gdiplus::Pen pen(color(0x{stroke[1:]},{number(opacity)}),REAL({number(width)}));',
                     'pen.SetStartCap(Gdiplus::LineCapRound);pen.SetEndCap(Gdiplus::LineCapRound);pen.SetLineJoin(Gdiplus::LineJoinRound);g.DrawPath(&pen,&p);']
        result.append('{'+''.join(code)+'}')
    for child in node: result.extend(walk(child,matrix,alpha))
    return result

# Discard only the SVG's outer y-axis flip: Painter already draws in y-up space.
outer = next(n for n in root if n.tag.endswith('g'))
assert len(outer) == 5
print('// Generated by scripts/generate-tree.py from the final macOS vector.')
print('// SVG SHA-256: '+hashlib.sha256(source.read_bytes()).hexdigest())
print('void treeArtwork(int layer){switch(layer){')
for index, layer in enumerate(outer):
    print(f'case {index}:{{')
    print('\n'.join(walk(layer)))
    print('}break;')
print('}}')
